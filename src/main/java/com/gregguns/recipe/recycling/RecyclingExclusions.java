package com.gregguns.recipe.recycling;

import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.Map;

/**
 * The GregGuns stacks that carry no GT recycling data on purpose, each with its reason, and the stacks whose data
 * another part of the code owns. Keys are {@link RecyclingCatalog} keys: a bare content name covers every variant of
 * the item; {@code name@damage} covers one. Plain Java, unit tested. The coverage scenario fails on any GregGuns stack
 * that has no data and is not listed here, so every gap is a decision.
 */
// Spec: docs/gregguns-spec/06-items/recycling.md (Exclusions; GGS-06-49, GGS-06-55)
public final class RecyclingExclusions {

    private static final String NO_RECIPE_WORLD = "world block: generated by structures, no recipe makes it";

    private static final Map<String, String> EXCLUDED = new LinkedHashMap<>();
    private static final Map<String, String> DELEGATED_PREFIXES = new LinkedHashMap<>();

    static {
        // Currency and creative items.
        EXCLUDED.put("coin", "currency for the Vending Machine; no recipe, and GT recycles no money");
        EXCLUDED.put("npc_egg", "creative spawn egg; no recipe");
        EXCLUDED.put("probe_tool_gun", "dev-only probe tool for the scenario harness; no recipe");
        // Technical blocks.
        EXCLUDED.put("missile_filler", "technical block that fills a placed missile's space; never an item in play");
        EXCLUDED.put("warhead_filler", "technical block that fills a placed warhead's space; never an item in play");
        EXCLUDED.put(
            "casings@2",
            "retired Reaction Casing, kept only so placed Retorts leave no holes (design record 0012); no recipe");
        // Fallout: no item data, or GT would turn free rubble into uranium (D84, D155).
        EXCLUDED.put("irradiated_earth", "fallout block; item data would recycle it into uranium (D84)");
        EXCLUDED.put("irradiated_rubble", "fallout drop; item data would recycle it into uranium (D84)");
        EXCLUDED.put("trinitite", "fallout block; item data would recycle it into uranium (D84, D155)");
        EXCLUDED.put("trinitite_shard", "fallout drop; item data would recycle it into uranium (D84, D155)");
        EXCLUDED.put("fallout_goo", "fallout block; item data would recycle it into uranium (D84, D155)");
        EXCLUDED.put("fallout_goo_item", "fallout drop; item data would recycle it into uranium (D84, D155)");
        // Silo complex and world structures.
        EXCLUDED.put(
            "complex_wall",
            "silo complex wall; no recipe and no recycling, so a complex is no casing mine (D205)");
        EXCLUDED.put("bug_nest", NO_RECIPE_WORLD);
        EXCLUDED.put("bug_nest_slime", NO_RECIPE_WORLD);
        EXCLUDED.put("bio_blob", NO_RECIPE_WORLD);
        EXCLUDED.put("camp_flag", NO_RECIPE_WORLD);
        // Made of materials GT gives no item data, so GT itself would recover nothing.
        EXCLUDED.put("part_stock_wooden", "three logs; GT gives logs no material data, so nothing comes back");
        // Consumables whose sheets rule out recycling data.
        EXCLUDED.put("antidote", "consumable; its sheet gives it no recycling data (antidote.md)");

        DELEGATED_PREFIXES.put("warhead_t", "warhead blocks: the warhead de-arming work owns their recycling data");
        DELEGATED_PREFIXES
            .put("inert_warhead_t", "inert warheads: the warhead de-arming work owns their recycling data");
    }

    /** Item families whose members share one reason, matched by the start of the content name. */
    private static final Map<String, String> EXCLUDED_PREFIXES = new LinkedHashMap<>();

    static {
        EXCLUDED_PREFIXES.put(
            "launcher_warhead_",
            "consumable launcher charge; its sheet gives it no recycling data (launcher-warheads.md)");
        // GT gives its own circuits no recycling data; a chip comes out of the Circuit Assembler like one.
        EXCLUDED_PREFIXES
            .put("missile_chip_t", "guidance chip from the Circuit Assembler: a circuit, and GT recycles no circuits");
        EXCLUDED_PREFIXES
            .put("missile_schematic_t", "an engraved guidance chip: a circuit, and GT recycles no circuits");
    }

    private RecyclingExclusions() {}

    /**
     * @param key a catalog key
     * @return why the stack carries no data on purpose, or null when it should carry data
     */
    public static String reason(String key) {
        String exact = EXCLUDED.get(key);
        if (exact != null) {
            return exact;
        }
        String content = content(key);
        String whole = EXCLUDED.get(content);
        if (whole != null) {
            return whole;
        }
        for (Map.Entry<String, String> entry : EXCLUDED_PREFIXES.entrySet()) {
            if (content.startsWith(entry.getKey())) {
                return entry.getValue();
            }
        }
        return null;
    }

    /**
     * @param key a catalog key
     * @return why another part of the code owns the stack's data, or null
     */
    public static String delegatedReason(String key) {
        String content = content(key);
        for (Map.Entry<String, String> entry : DELEGATED_PREFIXES.entrySet()) {
            if (content.startsWith(entry.getKey())) {
                return entry.getValue();
            }
        }
        return null;
    }

    /** @return the excluded families, content-name prefix to reason */
    public static Map<String, String> excludedPrefixes() {
        return Collections.unmodifiableMap(EXCLUDED_PREFIXES);
    }

    /** @return the exact and whole-item exclusions, key to reason */
    public static Map<String, String> excluded() {
        return Collections.unmodifiableMap(EXCLUDED);
    }

    private static String content(String key) {
        int at = key.indexOf('@');
        return at < 0 ? key : key.substring(0, at);
    }
}
