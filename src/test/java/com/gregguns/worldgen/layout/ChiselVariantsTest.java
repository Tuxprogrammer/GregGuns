package com.gregguns.worldgen.layout;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.ArrayList;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.gregguns.icbm.complex.palette.BlockRef;
import com.gregguns.icbm.complex.palette.ComplexPalette;
import com.gregguns.icbm.complex.palette.StyleSet;

/**
 * Every Chisel block and meta GregGuns places exists in Chisel 2.17.34-GTNH. Chisel draws its missing texture for a
 * meta it defines nothing at (the owner saw {@code chisel:glass_pane} meta 0 as ERROR panes), so a bad pair must fail
 * here, and {@link BlockRef#resolve} must skip one at runtime. The list is
 * {@code assets/gregguns/worldgen/chisel_variants.txt}, generated by {@code tools/chisel-variants/gen.py}.
 */
class ChiselVariantsTest {

    private static void add(List<BlockRef.Entry> out, BlockRef r) {
        if (r != null) out.addAll(r.chain());
    }

    @Test
    void everyComplexPaletteChiselPairIsDefinedByChisel() {
        List<BlockRef.Entry> all = new ArrayList<>();
        for (StyleSet s : ComplexPalette.sets()) {
            s.walls.forEach(r -> add(all, r));
            s.floors.forEach(
                p -> p.refs()
                    .forEach(r -> add(all, r)));
            s.ceilings.forEach(
                p -> p.refs()
                    .forEach(r -> add(all, r)));
            add(all, s.lampLit);
            add(all, s.lampUnlit);
            add(all, s.accent);
            add(all, s.worn);
            s.furniture.values()
                .forEach(r -> add(all, r));
        }
        List<String> bad = new ArrayList<>();
        int chisel = 0;
        for (BlockRef.Entry e : all) {
            if (!"chisel".equals(e.modId)) continue;
            chisel++;
            if (!ChiselVariants.names()
                .contains(e.name)) bad.add(e.key() + " (block not in the Chisel list)");
            else if (!ChiselVariants.isValid(e.name, e.meta)) bad.add(e.key());
        }
        assertTrue(chisel > 50, "the scan saw the palette's Chisel entries");
        assertTrue(bad.isEmpty(), "Chisel pairs Chisel does not define: " + bad);
    }

    @Test
    void everyPaletteKeyChiselPairIsDefinedByChisel() {
        PaletteKeys keys = PaletteKeys.resolve(
            name -> new net.minecraft.block.Block(net.minecraft.block.material.Material.rock) {},
            n -> new net.minecraft.block.Block(net.minecraft.block.material.Material.rock) {},
            w -> assertTrue(false, w));
        assertFalse(keys.get("glass_pane").fallback, "the glass pane key uses Chisel's pane");
        assertFalse(keys.get("gold_plate").fallback, "the gold plate key uses Chisel's gold");
    }

    @Test
    void glassPaneMetaZeroIsNotDefined() {
        assertFalse(ChiselVariants.isValid("glass_pane", 0));
        assertTrue(ChiselVariants.isValid("glass_pane", 2));
        assertTrue(ChiselVariants.isValid("not_a_listed_block", 0));
    }

    @Test
    void resolveSkipsAChiselMetaChiselDoesNotDefine() {
        BlockRef r = BlockRef.of(BlockRef.e("chisel", "glass_pane", 0), BlockRef.v("glass_pane", 0));
        assertTrue(r.resolve((m, n) -> true).modId.equals("minecraft"));
        BlockRef ok = BlockRef.of(BlockRef.e("chisel", "glass_pane", 2), BlockRef.v("glass_pane", 0));
        assertTrue(ok.resolve((m, n) -> true).modId.equals("chisel"));
    }
}
