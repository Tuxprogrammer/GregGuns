"""Regenerate pack_items.txt: the pack item ids that GregGuns quest data may name.

usage: python -I tools/questbook/pack_items.py <pack .minecraft folder> [--out tools/questbook/pack_items.txt]

The list is every item id the pack itself uses, so each one is known to resolve in the pack:
  - every stack id in config/betterquesting/DefaultQuests (tasks, rewards, icons), GT machines as
    gregtech:gt.blockmachines@<damage> because the damage picks the machine;
  - every ItemName in config/EnhancedLootBags/LootBags.xml;
  - every Pam's HarvestCraft food: item.<name>.name keys in the harvestcraft jar's en_US.lang (read as text only).
gregguns: ids are not listed; QuestbookResourcesTest checks those against the mod's own registry.
Names only (facts about the pack), sorted, one per line. Python 3, standard library only.
"""
import argparse
import glob
import json
import os
import re
import sys
import zipfile

GT_MACHINES = 'gregtech:gt.blockmachines'


def quest_ids(dq):
    out = set()

    def walk(o):
        if isinstance(o, dict):
            if 'id:8' in o and 'Damage:2' in o:
                out.add('%s@%d' % (GT_MACHINES, o['Damage:2']) if o['id:8'] == GT_MACHINES else o['id:8'])
            for v in o.values():
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    for path in glob.glob(os.path.join(dq, 'Quests', '**', '*.json'), recursive=True):
        with open(path, encoding='utf8') as fh:
            walk(json.load(fh))
    return out


def main(mc, out):
    ids = quest_ids(os.path.join(mc, 'config', 'betterquesting', 'DefaultQuests'))
    with open(os.path.join(mc, 'config', 'EnhancedLootBags', 'LootBags.xml'), encoding='utf8') as fh:
        ids |= set(re.findall(r'ItemName="([^"]+)"', fh.read()))
    jars = glob.glob(os.path.join(mc, 'mods', 'harvestcraft-*.jar'))
    if len(jars) != 1:
        print('expected one harvestcraft jar, found %d' % len(jars), file=sys.stderr)
        return 1
    with zipfile.ZipFile(jars[0]) as jar:
        lang = jar.read('assets/harvestcraft/lang/en_US.lang').decode('utf8')
    ids |= {'harvestcraft:' + n for n in re.findall(r'(?m)^item\.([A-Za-z0-9_]+)\.name=', lang)}
    ids = sorted(i for i in ids if ':' in i and not i.startswith('gregguns:'))
    head = ['# Pack item ids quest data may name (GTNH 2.9.0-RC-2): every id in its DefaultQuests and LootBags.xml,',
            '# and every Pam\'s HarvestCraft food in its lang. GT machines are gregtech:gt.blockmachines@<damage>.',
            '# Generated by tools/questbook/pack_items.py; do not edit by hand.']
    with open(out, 'w', encoding='utf8', newline='\n') as fh:
        fh.write('\n'.join(head + ids) + '\n')
    print('wrote %d ids to %s' % (len(ids), out))
    return 0


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('minecraft', help='the pack instance .minecraft folder')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pack_items.txt'))
    a = ap.parse_args()
    sys.exit(main(a.minecraft, a.out))
