"""Connected-texture (CTM) tile sets for the GregGuns base casings.

    python -I -X utf8 tools/asset-gen/ctm.py            # tiles, properties files and credit rows
    python -I -X utf8 tools/asset-gen/ctm.py --check    # also assert tile 0 equals the shipped base texture

Writes, for each connected casing, assets/gregguns/mcpatcher/ctm/<name>/{0..46}.png and <name>.properties in
the MCPatcher/OptiFine "ctm" format (47 tiles). In the pack that format is read by Angelica's bundled
MCPatcherForge; without it the block keeps its normal icon (textures/blocks/casings/<name>.png), which is tile 0.

The 47-tile layout is the documented MCPatcher/OptiFine one: tile 0 is the isolated block (frame on all four
sides), tile 26 the fully surrounded one (no frame), tile 46 has a notch in every corner. Each tile is four 8x8
quadrants, and a quadrant only depends on the two sides and the one diagonal that touch it, so LAYOUT below lists
the four quadrant states per tile:

    C  both sides of the corner are framed (outer corner)
    E  only the top (upper quadrants) or bottom (lower quadrants) side is framed
    S  only the left (left quadrants) or right (right quadrants) side is framed
    N  both neighbors connect but the diagonal one does not: a notch in the corner
    F  fully surrounded, plain panel

Each string reads top-left, top-right, bottom-left, bottom-right. The painters in blockart.py take an Edges
(which sides are framed, which corners are notched) and draw the same fill, ribs and motif in every tile, so the
interior continues seamlessly from block to block.
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))   # python -I does not add the script dir

import blockart as ba
import outroot
from blocktex import Canvas, rng_for, seed_for

LAYOUT = (
    "CCCC", "CECE", "EEEE", "ECEC", "CESN", "ECNS", "SNSN", "EENN", "NFNN", "NNNF",
    "FNFN", "FFNN", "CCSS", "CESF", "EEFF", "ECFS", "SNCE", "NSEC", "NNEE", "NSNS",
    "FNNN", "NNFN", "NNFF", "NFNF", "SSSS", "SFSF", "FFFF", "FSFS", "SNSF", "EEFN",
    "SFSN", "EENF", "FFFN", "FFNF", "NFFN", "FNNF", "SSCC", "SFCE", "FFEE", "FSEC",
    "NFEE", "FSNS", "FNEE", "NSFS", "FNFF", "NFFF", "NNNN",
)
assert len(LAYOUT) == 47 and len(set(LAYOUT)) == 47

# name (the file under textures/blocks/casings/) -> (painter, meta of gregguns:casings, title for the credits)
# The metas are GregGunsCasings.WORKS_CASING, GANTRY_CASING and BASTION_IRON .. BASTION_CARBON; CtmCasingsTest
# checks that they agree. Ram Housing, Gantry Beam/Hoist, Repair Cradle, Reaction Casing and Radar Casing stay single.
CASINGS = {
    "works_casing": (ba.works_casing, 0),
    "gantry_casing": (ba.gantry_casing, 3),
    "bastion_plating_iron": (ba.bastion_iron, 7),
    "bastion_plating_steel": (ba.bastion_steel, 8),
    "bastion_plating_aluminum": (ba.bastion_aluminum, 9),
    "bastion_plating_carbon": (ba.bastion_carbon, 10),
}
BLOCK = "gregguns:casings"
SOURCES = "https://github.com/GTNewHorizons/Angelica/blob/2.2.28/src/main/java/com/prupe/mcpatcher/ctm/"


def quadrant_state(h: bool, v: bool, corner: bool) -> str:
    """State of one quadrant from its horizontal neighbor, vertical neighbor and diagonal neighbor."""
    if h and v:
        return "F" if corner else "N"
    if h:
        return "E"      # the sideways neighbor connects, the one above/below does not: frame along the top/bottom
    if v:
        return "S"
    return "C"


def tile_index(left, down_left, down, down_right, right, up_right, up, up_left) -> int:
    """The tile a face shows, from whether each of its eight in-plane neighbors connects (viewed from the front of
    the face, up as the texture's up)."""
    key = (quadrant_state(left, up, up_left) + quadrant_state(right, up, up_right)
           + quadrant_state(left, down, down_left) + quadrant_state(right, down, down_right))
    return LAYOUT.index(key)


def edges_for(state: str, quad: int) -> "ba.Edges":
    """Edges for one quadrant (0 tl, 1 tr, 2 bl, 3 br) in a given state; the other two sides are left unframed."""
    top, left = quad < 2, quad % 2 == 0
    t, s = state in "CE", state in "CS"
    corner = ("t" if top else "b") + ("l" if left else "r")
    return ba.Edges(t=t and top, b=t and not top, l=s and left, r=s and not left,
                    notch=(corner,) if state == "N" else ())


def build_tile(painter, asset_id: str, index: int) -> Canvas:
    out = Canvas(16)
    for quad, state in enumerate(LAYOUT[index]):
        full = painter(rng_for(asset_id), edges_for(state, quad))[0]
        x0, y0 = 8 * (quad % 2), 8 * (quad // 2)
        out.a[y0:y0 + 8, x0:x0 + 8] = full.a[y0:y0 + 8, x0:x0 + 8]
    return out


def properties(name: str, meta: int) -> str:
    return (
        f"# Connected textures for {name} (meta {meta} of {BLOCK}). Generated by tools/asset-gen/ctm.py; do not edit.\n"
        "# Read by Angelica's bundled MCPatcherForge (method=ctm, the standard 47-tile layout); without it the block\n"
        f"# shows textures/blocks/casings/{name}.png, which is tile 0.\n"
        f"# Source: {SOURCES}TileOverride.java (matchBlocks, metadata, connect=block compares block and metadata)\n"
        "method=ctm\n"
        f"matchBlocks={BLOCK}\n"
        f"metadata={meta}\n"
        "connect=block\n"
        "tiles=0-46\n"
    )


def write_all(check: bool) -> None:
    root = outroot.RES / "mcpatcher" / "ctm"
    rows = []
    for name, (painter, meta) in CASINGS.items():
        asset_id = f"block.casing.{name}"
        d = root / name
        d.mkdir(parents=True, exist_ok=True)
        for i in range(47):
            tile = build_tile(painter, asset_id, i).image()
            tile.save(d / f"{i}.png", optimize=True)
            if i == 0 and check:
                base = painter(rng_for(asset_id))[0].image()
                assert list(tile.getdata()) == list(base.getdata()), f"{name}: tile 0 differs from the base painter"
        (d / f"{name}.properties").write_text(properties(name, meta), encoding="utf-8", newline="\n")
        rows.append([f"{asset_id}.ctm", f"src/main/resources/assets/gregguns/mcpatcher/ctm/{name}/ (0.png to 46.png)",
                     "tools/asset-gen/ctm.py", seed_for(asset_id),
                     "procedural connected-texture set, 47 tiles in the MCPatcher/OptiFine ctm layout, cut from the "
                     "casing painter (blockart.py) with the frame on chosen sides; tile 0 is the base texture",
                     "MIT", "2026-10-27"])
    out = outroot.CREDITS_DIR / "ctm.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["asset", "path", "generator", "seed", "method", "license", "date"])
        w.writerows(rows)
    print("wrote", len(CASINGS), "tile sets under", root)


if __name__ == "__main__":
    write_all("--check" in sys.argv)
