"""Lists the (block, meta) pairs Chisel registers variations for, read from Chisel's Features.java.

Usage: python -I tools/chisel-variants/gen.py <path to Features.java at the pack's tag> > chisel_variants.txt
Source: https://github.com/GTNewHorizons/Chisel/blob/2.17.34-GTNH/src/main/java/team/chisel/Features.java
(clone with: python -I tools/gtnh-reference/gtnh_ref.py clone Chisel)

Each `<var>.carverHelper.addVariation("<lang>", <meta>, ...)` with a literal meta adds <meta> to the block the same
Features section registers under `carverHelper.registerAll/registerBlock(<var>, "<registry name>")`. Variations added
in loops (hexPlating, antiBlock, futuraCircuit: one per dye, metas 0 to 15) are listed in LOOPED. Blocks not listed
here are not checked. Chisel's own meta 0 of a group that wraps a vanilla block (glass_pane, gold_block, bookshelf)
has no variation, so it draws the missing texture; that is what this list exists to catch.
"""
import collections
import re
import sys

LOOPED = {"hexPlating": range(16), "antiBlock": range(16), "futuraCircuit": range(16)}

src = open(sys.argv[1]).read()
metas = collections.defaultdict(set)
names = {}
sec = None
pat = re.compile(
    r'^    ([A-Z_0-9]+) \{'
    r'|(\w+)\s*\.carverHelper\s*\.addVariation\(\s*"[^"]*",\s*(\d+)'
    r'|(\w+)\s*\.carverHelper\s*\.register(?:All|Block)\(\s*\w+,\s*"([^"]+)"',
    re.M,
)
for m in pat.finditer(src):
    if m.group(1):
        sec = m.group(1)
    elif m.group(2):
        metas[(sec, m.group(2))].add(int(m.group(3)))
    else:
        names[(sec, m.group(4))] = m.group(5)
out = collections.defaultdict(set)
for (s, v), ms in metas.items():
    if (s, v) in names:
        out[names[(s, v)]] |= ms
for n, r in LOOPED.items():
    out[n] |= set(r)
print("# Chisel 2.17.34-GTNH block variations: <registry name> <valid metas>")
print("# Generated by tools/chisel-variants/gen.py from Features.java at the 2.17.34-GTNH tag.")
for n in sorted(out):
    print(n, ",".join(map(str, sorted(out[n]))))
